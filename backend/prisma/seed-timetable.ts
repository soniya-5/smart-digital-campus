async function seedOfficialTimetable() {
  console.log('Seeding official college timetable for S.E. (III) Computer Engg (Classroom 005)...');

  // Clear any existing master timetable entries (where userId is null)
  await prisma.timetableEntry.deleteMany({
    where: { userId: null },
  });

  for (const entry of OFFICIAL_TIMETABLE_ENTRIES) {
    await prisma.timetableEntry.create({
      data: {
        userId: null,
        code: entry.code,
        subject: entry.subject,
        dayOfWeek: entry.dayOfWeek,
        startTime: entry.startTime,
        endTime: entry.endTime,
        location: entry.location,
        facultyName: entry.facultyName,
        batch: entry.batch,
        type: entry.type,
      },
    });
  }

  const count = await prisma.timetableEntry.count({ where: { userId: null } });
  console.log(`[SUCCESS] Seeded ${count} official timetable sessions from S.E. (III) Computer Engg schedule.`);
  await prisma.$disconnect();
}

seedOfficialTimetable().catch((err) => {
  console.error('[ERROR] Failed to seed timetable:', err);
  process.exit(1);
});
